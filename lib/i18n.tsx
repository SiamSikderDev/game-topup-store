const STR = { bn, en };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: typeof bn };
const LangCtx = createContext<Ctx>({ lang: "bn", setLang: () => {}, t: bn });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("bn");
  useEffect(() => {
    const s = localStorage.getItem("topupghor_lang");
    if (s === "en" || s === "bn") {
      setLangState(s);
      document.documentElement.lang = s;
    }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("topupghor_lang", l);
    document.documentElement.lang = l;
  };
  return <LangCtx.Provider value={{ lang, setLang, t: STR[lang] }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}
